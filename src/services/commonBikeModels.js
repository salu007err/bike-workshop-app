/**
 * Search/filter bike models by query with typo tolerance
 */
export function searchBikeModels(query, limit = 8) {
  const q = (query || '').toLowerCase().trim();
  if (!q) {
    return POPULAR_BIKE_MODELS.slice(0, limit);
  }

  // 1. Direct prefix / substring matches
  const exactMatches = POPULAR_BIKE_MODELS.filter((item) =>
    item.name.toLowerCase().includes(q)
  );

  if (exactMatches.length >= limit) {
    return exactMatches.slice(0, limit);
  }

  // 2. Word boundary matches
  const qWords = q.split(/\s+/).filter(Boolean);
  const wordMatches = POPULAR_BIKE_MODELS.filter((item) => {
    if (exactMatches.includes(item)) return false;
    const itemName = item.name.toLowerCase();
    return qWords.every((word) => itemName.includes(word));
  });

  return [...exactMatches, ...wordMatches].slice(0, limit);
}
